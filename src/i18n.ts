export const LangContext = createContext<{ lang: Lang; setLang: (lang: Lang) => void }>({
  lang: DEFAULT_LANG,
  setLang: () => {},
})

export function useLang() {
  return useContext(LangContext)
}

export function useText(): Dictionary {
  return dictionaries[useLang().lang]
}
